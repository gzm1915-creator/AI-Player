using System;
using System.Text.Json;
using AUTelemetryProbe;
static void Check(bool ok, string why) { if (!ok) throw new Exception(why); }
var self = PlayerControl.LocalPlayer;
var area = new PlayerVoteArea { PlayerId = 0 };
var other = new PlayerVoteArea { PlayerId = 1, DidVote = true, VotedForId = 2 };
var meeting = new MeetingHud { CurrentState = MeetingHud.MeetingStates.Discussion, playerStates = new[] { area, other } };
MeetingHud.Instance = meeting;
GameData.Instance.Players[0] = self.Data;
GameData.Instance.Players[1] = new();
Check(!MeetingVoting.Capture().CanVote, "discussion cannot vote");
Check(!MeetingVoting.TrySubmit(-1, out _, out _), "discussion RPC rejected");
meeting.CurrentState = MeetingHud.MeetingStates.NotVoted;
Check(MeetingVoting.Capture().CanVote, "actual voting phase permits vote");
Check(MeetingVoting.Capture().RemainingSeconds == 10, "short voting window observed");
meeting.discussionTimer = 4;
Check(MeetingVoting.Capture().RemainingSeconds == 6, "remaining voting time uses game timer");
GameOptionsManager.Instance!.CurrentGameOptions!.Voting = 0;
Check(MeetingVoting.Capture().RemainingSeconds == null, "infinite voting timer remains unknown");
GameOptionsManager.Instance.CurrentGameOptions.Voting = 10;
Check(MeetingVoting.Capture().TargetPlayerId == null, "never expose another player's vote");
foreach (int id in new[] { -2, 2, 253, 254, 255 })
    Check(!MeetingVoting.TrySubmit(id, out _, out _), "invalid target rejected");
GameData.Instance.Players[1].IsDead = true;
Check(!MeetingVoting.TrySubmit(1, out _, out _), "dead target rejected");
GameData.Instance.Players[1].IsDead = false;
GameData.Instance.Players[1].Disconnected = true;
Check(!MeetingVoting.TrySubmit(1, out _, out _), "disconnected target rejected");
GameData.Instance.Players[1].Disconnected = false;
self.Data.IsDead = true;
Check(!MeetingVoting.TrySubmit(-1, out _, out _), "dead self rejected");
self.Data.IsDead = false;
Check(MeetingVoting.TrySubmit(-1, out var already, out _) && !already, "skip submitted");
Check(meeting.RpcCalls == 1 && meeting.LastTarget == 253, "native skip constant");
Check(!area.DidVote && !MeetingVoting.Capture().HasVoted, "no optimistic local vote flag");
Check(MeetingVoting.Capture().State == "submitted", "pending separated from recorded");
Check(!MeetingVoting.TrySubmit(1, out _, out _) && meeting.RpcCalls == 1, "pending duplicate refused");
Check(MeetingVoting.Capture(DateTimeOffset.UtcNow.AddSeconds(6)).State == "unconfirmed", "timeout is not success");
area.DidVote = true; area.VotedForId = 253;
Check(MeetingVoting.Capture().HasVoted && MeetingVoting.Capture().TargetPlayerId == -1, "observed skip confirmation");
Check(MeetingVoting.TrySubmit(1, out already, out _) && already && meeting.RpcCalls == 1, "recorded vote idempotence");
area.DidVote = false;
MeetingVoting.Reset();
Check(MeetingVoting.TrySubmit(1, out _, out _) && meeting.LastTarget == 1, "eligible native player vote");
MeetingVoting.Reset();
foreach (var phase in new[] { MeetingHud.MeetingStates.Results, MeetingHud.MeetingStates.Proceeding, MeetingHud.MeetingStates.Animating }) {
    meeting.CurrentState = phase;
    Check(!MeetingVoting.TrySubmit(-1, out _, out _), "non-voting stage rejected");
}
meeting.playerStates = null;
Check(!MeetingVoting.Capture().Supported, "missing roster unavailable");
MeetingHud.Instance = null;
Check(!MeetingVoting.Capture().Supported, "closed meeting unavailable");
Console.WriteLine("PASS native voting: phases, roster, death/disconnect, skip=253, pending/recorded, duplicates, timeout and privacy (synthetic)");
MeetingLifecycleTests.Run();
